#!/usr/bin/env bash
# Regression test for scripts/check_commit_messages.sh and scripts/hooks/*
# using synthetic commits in throwaway repositories. gitleaks is replaced by a
# stub that records its arguments, so no network or real scanner is needed.
# Fake values only; nothing here is a real identifier.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
checker="$repo_root/scripts/check_commit_messages.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail=0
ok()  { printf 'ok    %s\n' "$1"; }
bad() { printf 'FAIL  %s\n' "$1"; fail=1; }

ai_host='claude''.ai'
trailer_key='Claude''-Session:'
fake_id='zz-fake-device-account-41'
mkdir -p "$work/private"
printf '%s\n' "$fake_id" > "$work/private/patterns.txt"
export BOWELNCA_PRIVATE_PATTERNS="$work/private/patterns.txt"

new_repo() {  # $1 dir; one clean base commit by a no-reply identity
  rm -rf "$1"; mkdir -p "$1"
  git -C "$1" init -q -b main
  git -C "$1" config user.name 'Test'
  git -C "$1" config user.email 'test@users.noreply.github.com'
  git -C "$1" config core.hooksPath /dev/null
  printf 'base\n' > "$1/a.txt"
  git -C "$1" add -A && git -C "$1" commit -q -m 'base'
}
commit_with() {  # $1 dir, $2 message, [$3 author e-mail]
  printf '%s\n' "$RANDOM" >> "$1/a.txt"
  git -C "$1" add -A
  if [ -n "${3:-}" ]; then
    git -C "$1" -c user.email="$3" commit -q -m "$2"
  else
    git -C "$1" commit -q -m "$2"
  fi
}
expect_reject() {  # $1 label, $2 message, [$3 e-mail]
  local d="$work/r" out
  new_repo "$d"; commit_with "$d" "$2" "${3:-}"
  if out="$(cd "$d" && bash "$checker" main~1..main 2>&1)"; then bad "accepted: $1"; else ok "rejects $1"; fi
  if grep -qF -- "$fake_id" <<<"$out" || grep -qF -- "session_0000TESTONLY" <<<"$out"; then bad "printed the matched value: $1"; fi
}

# Range mode.
d="$work/clean"; new_repo "$d"; commit_with "$d" "Add synthetic fixture

Co-Authored-By: Claude <noreply@anthropic.com>"
if (cd "$d" && bash "$checker" main~1..main >/dev/null); then ok "accepts a clean commit with a no-reply co-author"; else bad "clean commit rejected"; fi
expect_reject "private session link" "Fix x

see https://${ai_host}/code/session_0000TESTONLY"
expect_reject "session trailer" "Fix x

${trailer_key} https://example.invalid/x"
expect_reject "private artifact link" "Doc https://${ai_host}/artifact/TESTONLY"
expect_reject "secret-like string" "token ghp_$(printf 'a%.0s' {1..36})"
expect_reject "private identifier from the local pattern file" "Run as $fake_id"
expect_reject "personal author e-mail" "Normal message" "person@example.invalid"
d="$work/public"; new_repo "$d"; commit_with "$d" "Generated by https://${ai_host}/code"
if (cd "$d" && bash "$checker" main~1..main >/dev/null); then ok "accepts a public product link"; else bad "public product link rejected"; fi

# Message-file mode (commit-msg hook).
printf 'Fix\n\n%s x\n' "$trailer_key" > "$work/msg1"
if bash "$checker" --message-file "$work/msg1" >/dev/null 2>&1; then bad "message file with trailer accepted"; else ok "message file with trailer rejected"; fi
printf 'Fix the thing\n' > "$work/msg2"
if bash "$checker" --message-file "$work/msg2" >/dev/null 2>&1; then ok "clean message file accepted"; else bad "clean message file rejected"; fi

# Hooks, with a stub gitleaks. The hooks run in a copy of the scripts so the
# repository root they resolve is the fixture repository.
stub_bin="$work/bin"; mkdir -p "$stub_bin"
cat > "$stub_bin/gitleaks" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >> "${GITLEAKS_STUB_LOG:?}"
[ ! -e "${GITLEAKS_STUB_FAIL:-/nonexistent}" ]
EOF
chmod +x "$stub_bin/gitleaks"
export GITLEAKS_STUB_LOG="$work/gitleaks.log"

hook_repo() {  # $1 dir: fixture repo that passes the repository policy, hooks installed
  new_repo "$1"
  mkdir -p "$1/scripts/hooks" "$1/docs"
  cp "$repo_root/scripts/check_repo_policy.sh" "$repo_root/scripts/check_commit_messages.sh" "$1/scripts/"
  cp "$repo_root/scripts/hooks/"* "$1/scripts/hooks/"
  printf 'x\n' > "$1/CLAUDE.md"; printf 'x\n' > "$1/docs/DEVELOPMENT_PLAN_v1.2.md"
  printf 'x\n' > "$1/docs/DATA_GOVERNANCE.md"; printf 'x\n' > "$1/.gitignore"; printf 'x\n' > "$1/.gitleaks.toml"
  git -C "$1" rm -q --cached a.txt && rm -f "$1/a.txt"
  git -C "$1" add -A && git -C "$1" commit -q -m 'fixture layout'
  git -C "$1" config core.hooksPath scripts/hooks
}

d="$work/hooks"; hook_repo "$d"
# commit-msg blocks a trailer; pre-commit runs gitleaks on staged changes.
printf 'x\n' > "$d/docs/n.md"; git -C "$d" add -A
if PATH="$stub_bin:$PATH" git -C "$d" commit -q -m "x

${trailer_key} y" 2>/dev/null; then bad "commit-msg hook allowed a session trailer"; else ok "commit-msg hook blocks a session trailer"; fi
: > "$GITLEAKS_STUB_LOG"
if PATH="$stub_bin:$PATH" git -C "$d" commit -q -m "Add note" 2>/dev/null; then ok "hooks allow a clean commit"; else bad "hooks blocked a clean commit"; fi
grep -q -- '--pre-commit --staged --redact' "$GITLEAKS_STUB_LOG" && ok "pre-commit runs gitleaks on staged changes, redacted" || bad "pre-commit did not run gitleaks as expected"
# pre-commit fails closed without gitleaks and when gitleaks reports a leak.
printf 'y\n' >> "$d/docs/n.md"; git -C "$d" add -A
if BOWELNCA_GITLEAKS="$work/missing-gitleaks" git -C "$d" commit -q -m "More" 2>/dev/null; then bad "pre-commit passed without gitleaks"; else ok "pre-commit fails closed without gitleaks"; fi
touch "$work/leak"
if GITLEAKS_STUB_FAIL="$work/leak" PATH="$stub_bin:$PATH" git -C "$d" commit -q -m "More" 2>/dev/null; then bad "pre-commit ignored a gitleaks finding"; else ok "pre-commit blocks on a gitleaks finding"; fi
# pre-commit blocks a private identifier.
printf 'ssh %s@h\n' "$fake_id" > "$d/docs/n.md"; git -C "$d" add -A
if PATH="$stub_bin:$PATH" git -C "$d" commit -q -m "More" 2>/dev/null; then bad "pre-commit allowed a private identifier"; else ok "pre-commit blocks a private identifier"; fi
git -C "$d" reset -q --hard

# pre-push: push to a bare remote; scans exactly the new commits.
remote="$work/remote.git"; git init -q --bare "$remote"
git -C "$d" remote add origin "$remote"
: > "$GITLEAKS_STUB_LOG"
if PATH="$stub_bin:$PATH" git -C "$d" push -q origin main 2>/dev/null; then ok "pre-push allows a clean new branch"; else bad "pre-push blocked a clean push"; fi
grep -q -- '--log-opts=' "$GITLEAKS_STUB_LOG" && ok "pre-push runs gitleaks over the pushed commits" || bad "pre-push did not run gitleaks"
# A pushed commit carrying a private link is blocked (bypass only the commit-time hooks).
printf 'z\n' >> "$d/docs/n.md"; git -C "$d" add -A
git -C "$d" -c core.hooksPath=/dev/null commit -q -m "x https://${ai_host}/code/session_0000TESTONLY"
if out="$(PATH="$stub_bin:$PATH" git -C "$d" push -q origin main 2>&1)"; then bad "pre-push allowed a private link"; else ok "pre-push blocks a private link in a commit message"; fi
grep -qF 'session_0000TESTONLY' <<<"$out" && bad "pre-push printed the private link"
[ "$(git -C "$remote" rev-parse main)" != "$(git -C "$d" rev-parse main)" ] && ok "blocked commit did not reach the remote" || bad "blocked commit reached the remote"
# pre-push fails closed without gitleaks.
git -C "$d" -c core.hooksPath=/dev/null commit -q --amend -m "Clean message"
if BOWELNCA_GITLEAKS="$work/missing-gitleaks" git -C "$d" push -q origin main 2>/dev/null; then bad "pre-push passed without gitleaks"; else ok "pre-push fails closed without gitleaks"; fi

if [ "$fail" -ne 0 ]; then exit 1; fi
printf 'PASS: commit-message checks and git hooks\n'

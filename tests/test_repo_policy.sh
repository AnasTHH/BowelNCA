#!/usr/bin/env bash
# Regression test for scripts/check_repo_policy.sh using synthetic fixtures in
# a throwaway git repository. No real data is created or read.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
checker="$repo_root/scripts/check_repo_policy.sh"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail=0

new_fixture_repo() {
  local dir="$1"
  rm -rf "$dir"; mkdir -p "$dir/docs"
  git -C "$dir" init -q
  printf 'x\n' > "$dir/CLAUDE.md"
  printf 'x\n' > "$dir/docs/DEVELOPMENT_PLAN_v1.2.md"
  printf 'x\n' > "$dir/docs/DATA_GOVERNANCE.md"
  printf 'x\n' > "$dir/.gitignore"
}

# Clean baseline must pass.
base="$work/clean"
new_fixture_repo "$base"
mkdir -p "$base/reports/evidence"
printf 'REDACTED-BY-HUMAN: AB 2026-11-25\nL4T R35 (release), REVISION: 6.4\ncuDNN 8.6.0.166 TensorRT 8.5.2.2\nfree: 15Gi\n' > "$base/reports/evidence/stage0_inventory_redacted.txt"
git -C "$base" add -A
if ! bash "$checker" "$base" >/dev/null; then printf 'FAIL: clean fixture rejected\n'; bash "$checker" "$base" || true; fail=1; fi

# Each case: "<path>|<content>" must be rejected.
cases=(
  'data/raw_dev/case01.txt|x'
  'src/pkg/data/derived/a.txt|x'
  'nested/locked_test/ids.txt|x'
  'second_labels/a.txt|x'
  'checkpoints/a.txt|x'
  'outputs/run1/metrics.txt|x'
  'logs/run.txt|x'
  'third_party/OctreeNCA/model.py|x'
  'scan.nii.gz|x'
  'model.pth|x'
  'cache.pkl|x'
  'slide.tiff|x'
  'run.log|x'
  'train.out|x'
  'events.out.tfevents.1|x'
  'stage0_inventory_local.txt|x'
  '.env|x'
  'reports/overlay_case3.png|x'
  'docs/notes.md|-----BEGIN OPENSSH PRIVATE KEY-----'
  'reports/evidence/no_header.txt|L4T R35'
  'reports/evidence/ip.txt|REDACTED-BY-HUMAN: AB 2026-11-25\nlisten 192.168.1.20'
  'reports/evidence/vpn.txt|REDACTED-BY-HUMAN: AB 2026-11-25\npeer 100.101.102.103'
  'reports/evidence/tsnet.txt|REDACTED-BY-HUMAN: AB 2026-11-25\nhost dev.tail1234.ts.net'
  'reports/evidence/key.txt|REDACTED-BY-HUMAN: AB 2026-11-25\nssh-ed25519 AAAAC3Nza'
  'reports/evidence/badheader.txt|REDACTED-BY-HUMAN: PENDING\nL4T R35'
  'reports/evidence-draft/noheader.md|L4T R35'
  'reports/evidence-draft/clean.md|REDACTION-STATUS: PENDING-HUMAN-APPROVAL\nCUDA 11.4.19-1'
  'docs/notes/evidence_draft/x.md|CUDA 11.4'
  'docs/inventory_notes.md|REDACTION-STATUS: PENDING-HUMAN-APPROVAL\nL4T R35'
  'reports/evidence/home.txt|REDACTED-BY-HUMAN: AB 2026-11-25\n/home/devuser/venv'
  'reports/evidence/dev.txt|REDACTED-BY-HUMAN: AB 2026-11-25\n/dev/mmcblk0p1 28G'
  'reports/evidence/mac.txt|REDACTED-BY-HUMAN: AB 2026-11-25\nether 00:1b:44:11:3a:b7'
  # Publication allowlist: unapproved paths and file types.
  'misc/notes.md|x'
  'scripts/tool.exe|x'
  'docs/table.csv|x'
  'reports/run.json|x'
  'env/xavier/settings.yaml|x'
  'Makefile|x'
)
# Private AI-assistant links and session trailers (built at run time so this
# file never contains a literal one).
ai_host='claude''.ai'
cases+=(
  "docs/notes.md|see https://${ai_host}/code/session_0000TESTONLY"
  "docs/notes.md|see https://${ai_host}/artifact/TESTONLY0000"
  "reports/x.md|https://${ai_host}/code/project/chan_TESTONLY?thread=1"
  "docs/notes.md|Claude""-Session: https://example.invalid/x"
)
for entry in "${cases[@]}"; do
  path="${entry%%|*}"
  content="${entry#*|}"
  dir="$work/case"
  new_fixture_repo "$dir"
  mkdir -p "$dir/$(dirname "$path")"
  printf '%b\n' "$content" > "$dir/$path"
  git -C "$dir" add -A -f
  if bash "$checker" "$dir" >/dev/null 2>&1; then
    printf 'FAIL: policy accepted %s\n' "$path"; fail=1
  fi
done

# Public product links are allowed.
dir="$work/public-link"
new_fixture_repo "$dir"
printf 'Generated by https://%s/code\n' "$ai_host" > "$dir/README.md"
git -C "$dir" add -A
if ! bash "$checker" "$dir" >/dev/null 2>&1; then printf 'FAIL: public product link rejected\n'; fail=1; fi

# Private identifier patterns from a file OUTSIDE the repository. The fake
# identifier must be reported by pattern number only, never printed.
fake_id='zz-fake-device-account-41'
mkdir -p "$work/private"
printf '# test patterns\n%s\nzz-fake-host-[0-9]+\n' "$fake_id" > "$work/private/patterns.txt"
dir="$work/private-id"
new_fixture_repo "$dir"
printf 'ssh %s@example\n' "$fake_id" > "$dir/docs/setup.md"
git -C "$dir" add -A
out="$(BOWELNCA_PRIVATE_PATTERNS="$work/private/patterns.txt" bash "$checker" "$dir" 2>&1 || true)"
grep -q 'private identifier (pattern #1)' <<<"$out" || { printf 'FAIL: private identifier not reported\n'; fail=1; }
if grep -q "$fake_id" <<<"$out"; then printf 'FAIL: private identifier value printed\n'; fail=1; fi
# Identifier in a file NAME is caught too.
dir="$work/private-name"
new_fixture_repo "$dir"
printf 'x\n' > "$dir/docs/zz-fake-host-7.md"
git -C "$dir" add -A
if BOWELNCA_PRIVATE_PATTERNS="$work/private/patterns.txt" bash "$checker" "$dir" >/dev/null 2>&1; then
  printf 'FAIL: private identifier in a file name accepted\n'; fail=1
fi
# The clean fixture passes with the pattern file.
if ! BOWELNCA_PRIVATE_PATTERNS="$work/private/patterns.txt" bash "$checker" "$base" >/dev/null 2>&1; then
  printf 'FAIL: clean fixture rejected with a private pattern file\n'; fail=1
fi
# A pattern file inside the repository is refused.
dir="$work/pattern-inside"
new_fixture_repo "$dir"
cp "$work/private/patterns.txt" "$dir/patterns.txt"
if BOWELNCA_PRIVATE_PATTERNS="$dir/patterns.txt" bash "$checker" "$dir" >/dev/null 2>&1; then
  printf 'FAIL: pattern file inside the repository accepted\n'; fail=1
fi
# Required but missing pattern file fails closed; absent and not required passes.
if BOWELNCA_PRIVATE_PATTERNS="$work/none.txt" BOWELNCA_REQUIRE_PRIVATE_PATTERNS=1 bash "$checker" "$base" >/dev/null 2>&1; then
  printf 'FAIL: missing required pattern file accepted\n'; fail=1
fi
if ! BOWELNCA_PRIVATE_PATTERNS="$work/none.txt" bash "$checker" "$base" >/dev/null 2>&1; then
  printf 'FAIL: optional missing pattern file rejected\n'; fail=1
fi

if [ "$fail" -ne 0 ]; then exit 1; fi
printf 'PASS: repository policy rejects all %d synthetic violations, the private-identifier cases and accepts clean trees\n' "${#cases[@]}"
